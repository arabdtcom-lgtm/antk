export type Language = 'ar' | 'en';
export type Currency = 'SAR' | 'USD' | 'EGP';

export function formatPrice(amount: number, currency: Currency, lang: Language): string {
  // Simple multi-currency rates relative to SAR (Saudi Riyal)
  // 1 USD = 3.75 SAR
  // 1 SAR = 8.00 EGP (approximate for rich display)
  let converted = amount;
  let symbol = 'ر.س';

  if (currency === 'USD') {
    converted = amount / 3.75;
    symbol = '$';
  } else if (currency === 'EGP') {
    converted = amount * 12; // Display rate
    symbol = lang === 'ar' ? 'ج.م' : 'EGP';
  } else {
    symbol = lang === 'ar' ? 'ر.س' : 'SAR';
  }

  const rounded = Math.round(converted).toLocaleString(lang === 'ar' ? 'ar-EG' : 'en-US');
  
  if (lang === 'ar') {
    return `${rounded} ${symbol}`;
  } else {
    return `${symbol}${rounded}`;
  }
}
